def pages(j):
    start = 1 if j == 1 else 22 + 20 * (j - 2)
    end = 21 if j == 1 else (604 if j == 30 else start + 19)
    return start, end

def ayat(j):
    s, a = JUZ_START[j - 1]
    es, ea = JUZ_START[j] if j < 30 else (115, 1)
    out = []
    while (s, a) != (es, ea):
        out.append((s, a))
        a += 1
        if a > COUNTS[s - 1]:
            s, a = s + 1, 1
    return out

def label(j):
    lst = ayat(j)
    (s1, a1), (s2, a2) = lst[0], lst[-1]
    p1, p2 = pages(j)
    return f"من {SURAH_NAMES[s1-1]} {a1} إلى {SURAH_NAMES[s2-1]} {a2} (ص {p1:02d} إلى ص {p2})"

